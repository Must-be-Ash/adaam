import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assetDirectory = resolve(projectRoot, "agent", "assets", "photon");
const outputPath = resolve(
  projectRoot,
  "agent",
  "lib",
  "photon-app-icon.generated.ts",
);

const [svg, png] = await Promise.all([
  readFile(
    resolve(assetDirectory, "logo-with-background-not-rounded.svg"),
    "utf8",
  ),
  readFile(
    resolve(assetDirectory, "logo-with-background-not-rounded@4x.png"),
  ),
]);

if (
  !svg.slice(0, 256).includes("<svg") ||
  svg.length > 64 * 1024 ||
  png.byteLength > 1024 * 1024 ||
  !png.subarray(0, 8).equals(
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  )
) {
  throw new Error("The Photon application icon assets have an unexpected shape.");
}

const generated = `// Generated by scripts/embed-photon-assets.mjs. Do not edit.
export const photonAppIconSvgSource = ${JSON.stringify(svg)};
export const photonAppIconPngBase64 = ${JSON.stringify(png.toString("base64"))};
`;

await writeFile(outputPath, generated, "utf8");
